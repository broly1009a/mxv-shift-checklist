/**
 * tt-symbol-mapping.config.ts
 *
 * Bảng quy chuẩn đối ứng mã hàng hóa (Symbol Mapping) giữa Trading Technologies (TT) và CoreCCP / MXV.
 * Phiên bản hoàn thiện cho 67 mặt hàng giao dịch (Futures, Options, LME).
 * Chuẩn Clean Architecture & Domain-Driven Design (DDD).
 */

export interface TtCommodityMetadata {
  stt: number;
  ttFamily: string;      // Mã hàng hóa trên TT (Family Name, ví dụ: 'CL', 'KE', 'ZC', 'ALI')
  mxvCode: string;       // Mã hàng hóa trên CoreCCP / MXV (ví dụ: 'CLE', 'KWE', 'ZCE', 'ALI')
  cqgCode: string;       // Mã CQG đối ứng (để tra cứu song song giai đoạn chuyển đổi)
  exchange: string;      // Sở giao dịch quốc tế (CME, CBOT, NYMEX, ICE, TOCOM, LME...)
  nameVn: string;        // Tên hàng hóa tiếng Việt
  instrument: string;    // Loại sản phẩm: Futures | Options | LME
  ttSample: string;      // Mẫu mã hợp đồng trên TT (ví dụ: 'CL Jan27', 'KE Dec26')
  mxvSample: string;     // Mẫu mã hợp đồng trên MXV / CoreCCP (ví dụ: 'CLEF27', 'KWEZ26')
  displayFormat: string; // Định dạng hiển thị bước giá (Decimal, Integer)
}

