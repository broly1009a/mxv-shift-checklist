import {
  Controller,
  Post,
  Body,
  UseGuards,
  HttpException,
  HttpStatus,
  Logger,
} from '@nestjs/common';
import * as fs from 'fs';
import { JwtAuthGuard } from '../../auth/jwt-auth.guard';
import { GttCheckerService } from '../services/recon/gtt-checker.service';

/**
 * Controller chuyên trách tiếp nhận Upload file liên quan đến Giá thanh toán (GTT):
 * - GTT.xlsx (sinh từ VBA macro để đọc danh sách hợp đồng)
 * - market.csv (file giá thị trường upload thủ công)
 * - hang_hoa.xlsx (danh mục đặc tả hàng hóa)
 */
@Controller(['api/v1/trading-ops', 'api/v1/bot-engine'])
@UseGuards(JwtAuthGuard)
export class GttUploadController {
  private readonly logger = new Logger(GttUploadController.name);

  constructor(private readonly gttService: GttCheckerService) {}

  /**
   * Upload GTT.xlsx file (generated by VBA macro) to server for contract list reading.
   */
  @Post('gtt-upload')
  async uploadGttFile(@Body() body: { base64: string; filename?: string }) {
    try {
      const targetPath = this.gttService.getGttXlsxPath();

      if (!body.base64) {
        throw new Error('Không có dữ liệu file được gửi lên.');
      }

      const buffer = Buffer.from(body.base64, 'base64');
      fs.writeFileSync(targetPath, buffer);

      this.logger.log(`GTT.xlsx uploaded successfully to: ${targetPath}`);
      return {
        success: true,
        message: 'Upload GTT.xlsx thành công!',
        path: targetPath,
      };
    } catch (err: any) {
      throw new HttpException(
        `Upload GTT.xlsx thất bại: ${err.message}`,
        HttpStatus.BAD_REQUEST,
      );
    }
  }

  /**
   * Upload market.csv file manually (alternative to auto-download).
   */
  @Post('market-csv-upload')
  async uploadMarketCsv(@Body() body: { base64: string; filename?: string }) {
    try {
      const targetPath = this.gttService.getMarketCsvPath();

      if (!body.base64) {
        throw new Error('Không có dữ liệu file được gửi lên.');
      }

      const buffer = Buffer.from(body.base64, 'base64');
      fs.writeFileSync(targetPath, buffer);

      this.logger.log(`market.csv uploaded successfully to: ${targetPath}`);
      return {
        success: true,
        message: 'Upload market.csv thành công!',
        path: targetPath,
      };
    } catch (err: any) {
      throw new HttpException(
        `Upload market.csv thất bại: ${err.message}`,
        HttpStatus.BAD_REQUEST,
      );
    }
  }

  /**
   * Upload hang_hoa.xlsx file manually containing commodity specifications.
   */
  @Post('commodity-upload')
  async uploadCommodityFile(
    @Body() body: { base64: string; filename?: string },
  ) {
    try {
      const targetPath = this.gttService.getHangHoaXlsxPath();

      if (!body.base64) {
        throw new Error('Không có dữ liệu file được gửi lên.');
      }

      const buffer = Buffer.from(body.base64, 'base64');
      fs.writeFileSync(targetPath, buffer);

      this.logger.log(`hang_hoa.xlsx uploaded successfully to: ${targetPath}`);
      return {
        success: true,
        message: 'Upload file hàng hóa thành công!',
        path: targetPath,
      };
    } catch (err: any) {
      throw new HttpException(
        `Upload file hàng hóa thất bại: ${err.message}`,
        HttpStatus.BAD_REQUEST,
      );
    }
  }
}
